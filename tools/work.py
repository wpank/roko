def edit_front(path: Path, fn) -> str:
    m = re.match(r"(\+\+\+\n)(.*?)(\n\+\+\+\n?)(.*)", path.read_text(), re.S)
    return m.group(1) + fn(m.group(2)) + m.group(3) + m.group(4)


