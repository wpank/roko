PROSE = re.compile(r"\((?:the |test |a |or |e\.g|proxy|better|interim|must |see |settled|live |requires|then )|interim static|A named test|; better|must add\)|\bshould\b", re.I)
CT = re.compile(r"^cargo test -p (?P<crate>[a-z0-9_-]+)(?P<flags>(?: --(?:lib|bins?(?: [a-z0-9_-]+)?|test [A-Za-z0-9_-]+|all-features|release))*)(?: (?P<filt>[A-Za-z0-9_:]+))?(?: --.*)?$")


def strip_note(s: str) -> str:
    """Drop a trailing prose note from a suggested command: 'cmd  (the fix must add …)' → 'cmd'."""
    q, depth = None, 0
    for i, c in enumerate(s):
        if q:
            if c == q:
                q = None
            continue
        if c in "'\"":
            q = c
            continue
        if c == "(":
            if depth == 0 and i and s[i - 1] == " " and re.match(r"\((?:[a-z]+ ){1,}|\(e\.g|\(proxy|\(or |\(a ", s[i:]):
                return s[:i].rstrip(" ;,")
            depth += 1
        elif c == ")":
            depth -= 1
        elif depth == 0 and (s.startswith("; ", i) or s.startswith(", plus ", i) or s.startswith(". The current", i)
                             or (s.startswith(". ", i) and s[i + 2:i + 3].isupper())):
            return s[:i].rstrip(" ;,")
    return s


def cargo_guard(seg: str) -> str | None:
    m = CT.match(seg.strip())
    if not m:
        return None
    crate, flags, filt = m.group("crate"), m.group("flags") or "", m.group("filt")
    tm = re.search(r"--test ([A-Za-z0-9_-]+)", flags)
    if not filt:
        return f"test -f crates/{crate}/tests/{tm.group(1)}.rs" if tm else None
    name = filt.split("::")[-1]
    return f"grep -rqE 'fn {name}[A-Za-z0-9_]*' crates/{crate}/" if name.endswith("_") else f"grep -rqw 'fn {name}' crates/{crate}/"


def validate_suggestion(s: str, want_green: bool):
    """A suggested verify command is adopted only if it is a clean command whose static part is red now for an open item
    (green for a done one). A cargo-only command gets a `grep 'fn <test>'` guard so an unwritten test cannot pass vacuously."""
    for cand in (s, strip_note(s)):
        cand = cand.strip()
        if not cand or PROSE.search(cand) or cand[0].isupper():
            continue
        parts = split_and(cand)
        static = static_prefix(cand)
        if not static:
            g = cargo_guard(parts[0]) if parts else None
            if not g:
                continue
            cand, static = f"{g} && {cand}", g
        if (run_shell(static, 60) == 0) == want_green:
            return cand
    return None


def valid_anchor(a: str) -> bool:
    path, sym = anchor_parts(a)
    if not path:
        return True
    p = REPO / path
    if not p.exists():
        return False
    if sym and p.is_file():
        return re.search(r"\b" + re.escape(sym) + r"\b", p.read_text(errors="replace")) is not None
    return True


def cmd_apply_verdicts(a):
    """Apply one JSON object per line: {id, verdict, evidence, commit, duplicate_of, note, anchors, verify_sound, verify_suggestion}.
    Verdicts: done | in_progress | open | partial | superseded | duplicate | unclear (see tools/work_sweep_brief.md)."""
    snap = {r["id"]: r for r in json.load(open(a.snapshot))}
    verdicts = {}
    for f in a.files:
        for ln in open(f):
            if ln.strip():
                o = json.loads(ln)
                verdicts[o["id"]] = o
    idx = index()
    by = a.by or f"work sweep {dt.date.today().isoformat()} (static check)"
    stats = Counter()
    for iid, o in verdicts.items():
        it, seen = idx.get(iid), snap.get(iid, {})
        if it is None:
            print(f"SKIP {iid}: no such item")
            continue
        if seen and it["status"] != seen.get("status"):
            print(f"SKIP {iid}: status changed since the snapshot ({seen.get('status')} → {it['status']})")
            continue
        v = o["verdict"]
        status = {"done": "done", "duplicate": "superseded", "superseded": "superseded", "in_progress": "in_progress"}.get(v)
        if it["status"] == "in_progress" and v in ("open", "partial"):
            status = "open"
        notes = []
        cur = [x.get("command", "") for x in it.get("verify") or []]
        verify = None
        sug = (o.get("verify_suggestion") or "").strip()
        if sug and (o.get("verify_sound") is False or not cur):
            good = validate_suggestion(sug, want_green=v in ("done", "in_progress"))
            if good:
                verify = [good]
            elif o.get("verify_sound") is False:
                notes.append(f"The [[verify]] command is unsound. Proposed replacement, not yet validated: `{sug}`.")
        if verify is None and v in ("open", "partial"):
            passing = [c for c in cur if static_prefix(c) == c and run_shell(c, 60) == 0]
            if passing:
                verify = [c for c in cur if c not in passing]
                notes += [f"Removed [[verify]] `{c}`: it passes while the problem still exists." for c in passing]
        anchors = None
        if o.get("anchors"):
            good = [x for x in o["anchors"] if isinstance(x, str) and valid_anchor(x)]
            if any("/" in x for x in good) and good != it.get("anchors"):
                anchors = good
        closed = None
        if status in ("done", "superseded"):
            ev = o.get("evidence", "")
            if v == "duplicate":
                ev = f"Duplicate of {o.get('duplicate_of')} (the older item; keep that ID). {ev}"
            closed = {"at": dt.date.today().isoformat(), "commit": o.get("commit") if v == "done" else None, "by": by, "evidence": ev}
        note = (o.get("note") or "").strip()
        if note:
            today = dt.date.today().isoformat()
            notes.insert(0, note if today in note[:60] else f"Checked {today}: {note}")
        text = rewrite_item(it, status=status, closed=closed, verify=verify, anchors=anchors,
                            duplicate_of=o.get("duplicate_of") if v == "duplicate" else None,
                            verified=v != "unclear", rev=seen.get("head"), note="\n\n".join(notes) or None)
        stats[v] += 1
        if not a.dry_run:
            it["_path"].write_text(text)
    print(("would apply " if a.dry_run else "applied ") + json.dumps(stats))


