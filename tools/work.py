def sync_candidates(items):
    """[(item, kind, detail)] for open items that a commit trailer or a passed plan task says are closed."""
    opened = {i["id"]: i for i in items if i.get("status") in OPEN}
    out = []
    for sha, date, subject, body, _ in commit_log(names=False):
        for m in CLOSE_RE.finditer(subject + "\n" + body):
            for iid in ID_ANY.findall(m.group(1)):
                it = opened.get(iid)
                if it and date >= str(it.get("created") or ""):
                    out.append((it, "commit", (sha, subject)))
    for iid, rows in plan_closes().items():
        it = opened.get(iid)
        for plan, task, verdict, run_id in rows:
            if it and verdict == "passed":
                out.append((it, "plan", (plan, task, run_id)))
    seen, uniq = set(), []
    for c in out:
        if c[0]["id"] not in seen:
            seen.add(c[0]["id"])
            uniq.append(c)
    return uniq


def cmd_sync(a, quiet=False):
    items = [i for k in ROOTS for i in load(k)[0]]
    if not a.dry_run:
        prune_claims()
    # Its closures are logged as `reconciled`, under the syncing session (the commit hook passes its session id).
    session = session_name(getattr(a, "session", None), getattr(a, "hook_session", None), "sync")
    closed, conflicts = [], []
    for it, kind, det in sync_candidates(items):
        state = static_verify_state(it)
        where = f"commit {det[0]} ({det[1][:70]})" if kind == "commit" else f"plan task {det[0]}#{det[1]} (run {det[2]})"
        if state == "red":
            conflicts.append(f"{it['id']}: {where} says it closes it, but the static part of its [[verify]] fails")
            continue
        if not a.dry_run:
            if kind == "commit":
                # A commit closure keeps its claim's executor; without a claim, nobody knows who did the work.
                close_item(it, commit=det[0], by="commit trailer", evidence=f"Closed by {det[0]}: {det[1]}",
                           executor=item_claim(it["id"]).get("executor") or "unknown", forced=False,
                           source="reconciled", session=session)
            else:
                close_item(it, run_id=det[2], by=f"plan:{det[0]}#{det[1]}",
                           evidence=f"Plan task {det[0]}#{det[1]} declares closes = [\"{it['id']}\"] and passed its gates (Graph checkpoint verdict: passed).",
                           executor="roko-plan", via="roko-plan", forced=False, source="reconciled", session=session)
        closed.append(f"{it['id']}: {'would close' if a.dry_run else 'closed'} ({where})")
    if not quiet or closed or conflicts:
        for s in closed + conflicts:
            print(s)
        if not closed and not conflicts:
            print("nothing to sync")
    return closed, conflicts


