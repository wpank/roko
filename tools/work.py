def sev_key(it):
    return (SEV.index(it.get("severity", "p3")) if it.get("severity") in SEV else 9, it.get("title", ""))


def line(it, root_rel: Path):
    rel = it["_path"].relative_to(root_rel)
    lv = it.get("last_verified")
    tag = f" · verified {lv}" if lv else ""
    kind = "" if it["kind"] == "gap" else f" [{it['kind']}]"
    size = f" · size {it['size']}" if it.get("size") else ""
    hold = f" · **on hold:** {it['hold']}" if it.get("hold") else ""
    return f"- **{it['severity'].upper()}** [{it['id']}]({rel}) {it['title']}{kind}{size}{tag}{hold}"


def render_root(root_key: str, items):
    root = ROOTS[root_key]
    today = max((str(i.get("updated") or i.get("created") or "") for i in items), default="")  # deterministic: newest item date
    opened = [i for i in items if i.get("status") in OPEN]
    verified = [i for i in opened if i.get("triage") == "verified"]
    unverified = [i for i in opened if i.get("triage") != "verified"]
    parked = [i for i in items if i.get("status") == "parked"]
    closed = [i for i in items if i.get("status") not in OPEN and i.get("status") != "parked"]
    by_sub = defaultdict(list)
    for it in verified:
        by_sub[it["subsystem"][0]].append(it)
    out = [f"# roko work status{' (local)' if root_key == 'local' else ''}", "", GEN_NOTE, "",
           f"As of {today} (newest item update), from `{root.relative_to(REPO)}/items/`. "
           f"{len(opened)} open ({len(verified)} verified, {len(unverified)} unverified imports) · {len(closed)} closed · "
           f"{len(parked)} parked (not planned; in `parked/`, revive with `work.py unpark <id>`). "
           "Format and rules: `work/README.md`.", "",
           "Kinds: " + ", ".join(f"{k} {v}" for k, v in sorted(Counter(i['kind'] for i in opened).items())), ""]
    out += ["## Open — verified", ""]
    for sub in sorted(by_sub, key=lambda s: (min(sev_key(i) for i in by_sub[s]), s)):
        out.append(f"### {sub}")
        out += [line(i, root) for i in sorted(by_sub[sub], key=sev_key)]
        out.append("")
    by_sub_u = defaultdict(list)
    for it in unverified:
        by_sub_u[it["subsystem"][0]].append(it)
    if unverified:
        sev_counts = Counter(i.get("severity") for i in unverified)
        out += ["## Open — unverified imports", "",
                f"{len(unverified)} imported items have not been checked against current code yet "
                f"({', '.join(f'{s} {sev_counts[s]}' for s in SEV if sev_counts[s])}). "
                "They are listed in `TRIAGE.md`; verify one, then set `triage = \"verified\"` or close it with evidence.", "",
                "| Subsystem | Unverified |", "|---|---|"]
        out += [f"| {sub} | {len(by_sub_u[sub])} |" for sub in sorted(by_sub_u, key=lambda s: -len(by_sub_u[s]))]
        out.append("")
    tr = [f"# Triage queue{' (local)' if root_key == 'local' else ''}", "", GEN_NOTE, "",
          f"{len(unverified)} open items imported without verification, highest severity first within each subsystem.", ""]
    for sub in sorted(by_sub_u, key=lambda s: (min(sev_key(i) for i in by_sub_u[s]), s)):
        tr.append(f"### {sub} ({len(by_sub_u[sub])})")
        tr += [line(i, root) for i in sorted(by_sub_u[sub], key=sev_key)]
        tr.append("")
    (root / "TRIAGE.md").write_text("\n".join(tr) + "\n")
    out += ["## Recently closed", ""]
    recent = sorted(closed, key=lambda i: str((i.get("closed") or {}).get("at") or i.get("updated") or ""), reverse=True)[:30]
    out += [f"- [{i['id']}]({i['_path'].relative_to(root)}) {i['title']} — {i['status']}" for i in recent] or ["- none"]
    (root / "STATUS.md").write_text("\n".join(out) + "\n")

    top = [i for i in verified if i.get("kind") != "decision" and i.get("severity") in ("p0", "p1")]
    top = sorted(top, key=sev_key)[:40]
    cl = ["# Open now (p0/p1, verified)", "", GEN_NOTE, "",
          f"{len(top)} of {len(verified)} verified open items. Full list: `STATUS.md`. Add items per `work/README.md`.", ""]
    cl += [line(i, root) for i in top] or ["- none"]
    (root / "CLAUDE-OPEN.md").write_text("\n".join(cl) + "\n")

    decs = sorted([i for i in opened if i.get("kind") in ("decision", "question")], key=sev_key)
    dl = ["# Open decisions", "", GEN_NOTE, "", f"{len(decs)} open.", ""]
    dl += [line(i, root) for i in decs] or ["- none"]
    (root / "DECISIONS.md").write_text("\n".join(dl) + "\n")

    drift = compute_drift(items)
    (root / "DRIFT.md").write_text("\n".join(render_drift(root, items, drift, head_rev())) + "\n")
    if root_key == "work":
        render_now(root, opened, drift)
    return len(opened), len(verified), len(unverified), len(closed), len(parked)


def now_key(it):
    rank = it.get("rank")
    return (rank if isinstance(rank, int) else 10**6,) + sev_key(it)


def render_now(root: Path, opened, drift=None):
    goals = load_goals()
    out = ["# Now", "", GEN_NOTE, "",
           "What to work on next: the top checked, open items of each goal, highest-priority goal first. "
           "Reorder or change goals in `goals.toml`; pin an item higher with `rank = 1` (lower first).", ""]
    summary = drift_summary(drift or {})
    if summary:
        out += [f"**Drift:** {summary}. Re-check them before relying on this list: `DRIFT.md`.", ""]
    for n, g in enumerate(goals, 1):
        mine = [i for i in opened if i.get("goal") == g["key"]]
        active = sorted((i for i in mine if i.get("status") == "in_progress"), key=now_key)
        blocked = [i for i in mine if i.get("status") == "blocked"]
        waiting = [i for i in mine if i.get("status") == "open"]
        held = [i for i in waiting if i.get("hold")]
        ready = sorted((i for i in waiting if i.get("triage") == "verified" and not i.get("hold")), key=now_key)
        top = ready[: int(g.get("now", 3))]
        unchecked = len([i for i in waiting if i.get("triage") != "verified" and not i.get("hold")])
        out += [f"## {n}. {g['title']}", ""]
        out += [line(i, root) for i in top] or ["- nothing checked and open"]
        rest = [f"{len(ready) - len(top)} more open"]
        rest += [f"in progress: {', '.join(i['id'] for i in active)}"] if active else []
        rest += [f"{len(blocked)} blocked"] if blocked else []
        rest += [f"on hold: {', '.join(i['id'] for i in held)}"] if held else []
        rest += [f"{unchecked} unchecked (`TRIAGE.md`)"] if unchecked else []
        out += ["", f"_{' · '.join(rest)} · `goal = \"{g['key']}\"`_", ""]
    later = [i for i in opened if not i.get("goal")]
    out += [f"{len(later)} open items have no goal (later); they are listed in `STATUS.md`."]
    (root / "NOW.md").write_text("\n".join(out) + "\n")


