def cmd_park(a):
    today, idx = dt.date.today().isoformat(), index()
    for iid in a.ids:
        it = idx.get(iid)
        if it is None or it.get("status") not in OPEN:
            sys.exit(f"{iid}: not found or not open")
        prev = it["status"]

        def edit(fm):
            fm = re.sub(r'^status = "[a-z_]+"$', 'status = "parked"', fm, count=1, flags=re.M)
            fm = re.sub(r"^updated = .*$", f"updated = {today}", fm, count=1, flags=re.M)
            return fm + f'\n\n[parked]\nat = {today}\nfrom_status = "{prev}"\nreason = {tomlstr(a.reason)}'

        move(it, edit_front(it["_path"], edit), "parked")
    print(f"parked {len(a.ids)}")


def cmd_unpark(a):
    today, idx = dt.date.today().isoformat(), index()
    for iid in a.ids:
        it = idx.get(iid)
        if it is None or it.get("status") != "parked":
            sys.exit(f"{iid}: not found or not parked")
        prev = (it.get("parked") or {}).get("from_status", "open")

        def edit(fm):
            fm = re.sub(r"\n*\[parked\]\n(?:[a-z_]+ = [^\n]*(?:\n|$))*", "\n\n", fm)
            fm = re.sub(r'^status = "parked"$', f'status = "{prev}"', fm, count=1, flags=re.M)
            fm = re.sub(r"^updated = .*$", f"updated = {today}", fm, count=1, flags=re.M)
            return re.sub(r"\n{3,}", "\n\n", fm).rstrip("\n")

        move(it, edit_front(it["_path"], edit), "items")
    print(f"unparked {len(a.ids)}")


