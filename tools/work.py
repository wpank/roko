#!/usr/bin/env python3
"""Work-graph tool: create, check, close, sync and render work/items (replaced later by `roko work`).

Usage:
  work.py id --kind gap --title "…" --created 2026-09-28 --source "…"   # print a hash ID
  work.py new --kind gap --title "…" --source "…" [--root work|local] [--subsystem a,b] [--severity p2] [--triage verified]
  work.py check [--strict]                                               # validate both roots (+ verify-command lint)
  work.py render                                                         # regenerate views, including DRIFT.md
  work.py park <id>… --reason "…"                                        # not planned: move to parked/
  work.py unpark <id>…                                                   # restore status, move back to items/

Picking up work (work/README.md, "For agents"):
  work.py next [--n 4] [--goal G] [--max-size M] [--json]   # top unclaimed items that don't touch the same files
  work.py claim <id>… --by "<who>" [--branch B] [--worktree PATH] [--session S]   # shared claim in the main tree's .roko/work-claims/
        [--executor claude-agent|claude-session|roko-plan|human] [--via work-batch|work-next|manual|roko-plan] [--size S|M|L]
  work.py release <id>… [--session S] [--reason verify-fail|blocked|decision-needed|conflict|timeout|session-limit]
  work.py claims                             # list live and stale claims

The development record (work/telemetry/README.md; not for workers): claim and release, run in the main checkout, append
an event to work/telemetry/events/<session>.jsonl (session: --session, else $WORK_SESSION, else --by). The orchestrator
logs what happens after the work:
  work.py event merged|post-verify|escape|intervention <id> [--merge-sha REV] [--conflicts N] [--fixups N] [--rc N] [--caused-by ID]

Keeping the graph current (work/README.md, "Keeping the graph current"):
  work.py close <id> --evidence "…" [--commit REV] [--run-id RUN] [--status done|wontfix|superseded] [--duplicate-of ID]
        [--model M] [--assist EXECUTOR]   # [closed] also gets the claim's executor, via, size and claimed_at
  work.py sync [--dry-run]                   # close items from `Closes: <id>` commit trailers and passed plan tasks with closes=[…]
  work.py drift [--json]                     # open items whose evidence may be out of date
  work.py touched [--rev REV|A..B]           # open items a commit (or range) touched or mentioned
  work.py verify [<id>…] [--closed-since DATE] [--static-only]   # run [[verify]] commands
  work.py apply-verdicts --snapshot drift.json <verdicts.jsonl>… [--dry-run]   # apply a sweep's agent verdicts
  work.py hook                               # Claude Code PostToolUse adapter (reads the hook payload on stdin)
"""
from __future__ import annotations

import argparse, datetime as dt, hashlib, json, os, re, subprocess, sys, time, tomllib
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(os.environ.get("WORK_REPO") or Path(__file__).resolve().parents[1])
ROOTS = {"work": REPO / "work", "local": REPO / ".roko" / "work-local"}
PREFIX = {"gap": "gap", "bug": "bug", "regression": "reg", "finding": "find", "decision": "dec", "spec": "spec", "question": "q"}
STATUSES = {"open", "in_progress", "blocked", "done", "wontfix", "superseded", "parked"}
OPEN = {"open", "in_progress", "blocked"}
TRIAGE = {"verified", "unverified"}
SEV = ["p0", "p1", "p2", "p3"]
REQUIRED = ["id", "kind", "title", "status", "triage", "severity", "subsystem", "created", "source"]
ID_RE = re.compile(r"^(gap|bug|reg|find|dec|spec|q)-[0-9a-f]{6,8}$")
ID_ANY = re.compile(r"\b(?:gap|bug|reg|find|dec|spec|q)-[0-9a-f]{6,8}\b")
# GitHub-style closing keywords followed by one or more item IDs: "Closes: bug-1a2b3c, gap-4d5e6f"
CLOSE_RE = re.compile(r"\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\b:?\s+((?:(?:gap|bug|reg|find|dec|spec|q)-[0-9a-f]{6,8}(?:\s*(?:,|and)\s*)?)+)", re.I)
GEN_NOTE = "<!-- GENERATED by work tooling from work/items — do not edit by hand -->"
GOALS_FILE = ROOTS["work"] / "goals.toml"
STALE_DAYS = 21
HEAVY = re.compile(r"^\s*(?:\(?\s*cd [^&]*&&\s*)?(?:cargo|npx|npm|pnpm|node|roko|target/|\./target|curl|gh )")


def set_repo(path) -> None:
    """Point the tool at another checkout (tests; the hook acts on the checkout a commit happened in)."""
    global REPO, ROOTS, GOALS_FILE
    REPO = Path(path).resolve()
    ROOTS = {"work": REPO / "work", "local": REPO / ".roko" / "work-local"}
    GOALS_FILE = ROOTS["work"] / "goals.toml"


def load_goals():
    return tomllib.loads(GOALS_FILE.read_text()).get("goal", []) if GOALS_FILE.exists() else []


def make_id(kind: str, title: str, created: str, source: str, n: int = 6) -> str:
    h = hashlib.sha256(f"{kind}|{title}|{created}|{source}".encode()).hexdigest()
    return f"{PREFIX[kind]}-{h[:n]}"


def slug(title: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return "-".join(s.split("-")[:7])[:60] or "item"


def parse(path: Path):
    text = path.read_text()
    m = re.match(r"\+\+\+\n(.*?)\n\+\+\+\n?(.*)", text, re.S)
    if not m:
        raise ValueError("missing +++ TOML front matter")
    meta = tomllib.loads(m.group(1))
    return meta, m.group(2)


def load(root_key: str):
    items, errors = [], []
    for sub in ("items", "parked"):
        d = ROOTS[root_key] / sub
        if not d.exists():
            continue
        for p in sorted(d.glob("*.md")):
            if p.name.startswith("_"):
                continue
            try:
                meta, body = parse(p)
            except Exception as e:  # noqa: BLE001
                errors.append(f"{p.relative_to(REPO)}: {e}")
                continue
            meta["_path"] = p
            meta["_body"] = body
            meta["_root"] = root_key
            meta["_dir"] = sub
            items.append(meta)
    return items, errors


def validate(items):
    errs, seen = [], {}
    goal_keys = {g["key"] for g in load_goals()}
    for it in items:
        if "goal" in it and it["goal"] not in goal_keys:
            errs.append(f"{it['_path'].relative_to(REPO)}: goal {it['goal']!r} is not in work/goals.toml")
        if "hold" in it and not (isinstance(it["hold"], str) and it["hold"].strip()):
            errs.append(f"{it['_path'].relative_to(REPO)}: hold must be a non-empty reason string")
        if "size" in it and it["size"] not in SIZES:
            errs.append(f"{it['_path'].relative_to(REPO)}: size must be one of {SIZES}")
        if "rank" in it and not isinstance(it["rank"], int):
            errs.append(f"{it['_path'].relative_to(REPO)}: rank must be an integer")
        p = it["_path"].relative_to(REPO)
        for k in REQUIRED:
            if k not in it or it[k] in ("", None):
                errs.append(f"{p}: missing {k}")
        if not ID_RE.match(str(it.get("id", ""))):
            errs.append(f"{p}: bad id {it.get('id')!r}")
        elif not it["_path"].name.startswith(it["id"] + "-"):
            errs.append(f"{p}: file name must start with id {it['id']}-")
        if it.get("id") in seen:
            errs.append(f"{p}: duplicate id {it['id']} (also {seen[it['id']]})")
        seen[it.get("id")] = p
        if it.get("kind") not in PREFIX:
            errs.append(f"{p}: bad kind {it.get('kind')!r}")
        elif ID_RE.match(str(it.get("id", ""))) and not it["id"].startswith(PREFIX[it["kind"]] + "-"):
            errs.append(f"{p}: id prefix does not match kind {it['kind']}")
        if it.get("status") not in STATUSES:
            errs.append(f"{p}: bad status {it.get('status')!r}")
        if it.get("triage") not in TRIAGE:
            errs.append(f"{p}: bad triage {it.get('triage')!r}")
        if it.get("severity") not in SEV:
            errs.append(f"{p}: bad severity {it.get('severity')!r}")
        if not isinstance(it.get("subsystem"), list) or not it.get("subsystem"):
            errs.append(f"{p}: subsystem must be a non-empty list")
        if it.get("status") == "done":
            closed = it.get("closed") or {}
            if not (closed.get("evidence") or closed.get("run_id") or closed.get("commit")):
                errs.append(f"{p}: status=done needs [closed] evidence/run_id/commit")
        if it.get("status") in ("wontfix", "superseded") and not (it.get("closed") or {}).get("evidence"):
            errs.append(f"{p}: status={it.get('status')} needs [closed].evidence")
        errs += [f"{p}: {e}" for e in check_closed(it.get("closed") or {})]
        if it.get("triage") == "verified" and not it.get("last_verified"):
            errs.append(f"{p}: triage=verified needs last_verified")
        if (it.get("status") == "parked") != (it.get("_dir") == "parked"):
            errs.append(f"{p}: parked items live in parked/, all other items in items/")
        if it.get("status") == "parked" and not ((it.get("parked") or {}).get("at") and (it.get("parked") or {}).get("reason")):
            errs.append(f"{p}: status=parked needs [parked] at and reason")
    ids = {it.get("id") for it in items}
    for it in items:
        links = it.get("links") or {}
        for key in ("depends_on", "blocks", "supersedes"):
            for ref in links.get(key, []) or []:
                if ID_RE.match(ref) and ref not in ids:
                    errs.append(f"{it['_path'].relative_to(REPO)}: links.{key} → unknown {ref}")
    return errs


# ---------------------------------------------------------------- verify commands

def split_and(cmd: str) -> list[str]:
    """Split a shell command on top-level `&&` (outside quotes and parentheses)."""
    parts, cur, q, depth, i = [], "", None, 0, 0
    while i < len(cmd):
        c = cmd[i]
        if q:
            cur += c
            if c == q:
                q = None
        elif c in "'\"":
            q = c
            cur += c
        elif c == "(":
            depth += 1
            cur += c
        elif c == ")":
            depth -= 1
            cur += c
        elif cmd.startswith("&&", i) and depth == 0:
            parts.append(cur.strip())
            cur, i = "", i + 2
            continue
        else:
            cur += c
        i += 1
    parts.append(cur.strip())
    return [p for p in parts if p]


def static_prefix(cmd: str) -> str:
    """The part of a verify command before its first cargo/npm/network step: cheap to run at any time."""
    out = []
    for part in split_and(cmd):
        if HEAVY.match(part) or re.match(r"^\(?\s*cd\s", part):
            break
        out.append(part)
    return " && ".join(out)


def run_shell(cmd: str, timeout: int = 120) -> int:
    try:
        return subprocess.run(cmd, shell=True, cwd=REPO, capture_output=True, text=True, timeout=timeout).returncode
    except subprocess.TimeoutExpired:
        return 124


def static_verify_state(it) -> str:
    """'green' if every verify command's static prefix passes, 'red' if any fails, 'none' if there is nothing static."""
    prefixes = [static_prefix(v.get("command", "")) for v in it.get("verify") or []]
    prefixes = [p for p in prefixes if p]
    if not prefixes:
        return "none"
    return "green" if all(run_shell(p, 60) == 0 for p in prefixes) else "red"


def _test_filter_exists(crate: str, filt: str) -> bool:
    """True if a cargo test filter names an existing test fn or module in the crate."""
    name = filt.split("::")[-1]
    where = ["--", f"crates/{crate}/"]
    return (git_ok("grep", "-q", "-w", f"fn {name}", *where) or git_ok("grep", "-q", "-w", f"mod {name}", *where)
            or bool(git("ls-files", f"crates/{crate}/**/{name}.rs", f"crates/{crate}/tests/{name}.rs").strip()))


def lint_verify(cmd: str) -> list[str]:
    """Patterns that make a verify command pass while the problem still exists."""
    warns = []
    for part in split_and(cmd):
        if re.search(r"\|\s*head\b", part) and not re.search(r"\|\s*grep -q", part.split("| head")[-1]):
            warns.append("pipes into `head`, so it exits 0 whatever grep finds")
        m = re.match(r"^cargo test -p (\S+)(.*)$", part)
        if m:
            args = m.group(2).split()
            target = any(a in ("--test", "--bin", "--example") for a in args)
            takes_value = {"--test", "--bin", "--example", "--bench", "--features", "--test-threads", "--skip", "-F"}
            filters, skip = [], False
            for x in args:
                if skip:
                    skip = False
                    continue
                if x in takes_value:
                    skip = True
                elif not x.startswith("-"):
                    filters.append(x)
            guarded = re.search(r"grep\b[^&]*\bfn |test -f ", cmd)
            if not filters and not target:
                warns.append(f"runs the whole `{m.group(1)}` test suite, which passes while the bug is present")
            elif filters and not guarded and not _test_filter_exists(m.group(1), filters[-1]):
                warns.append(f"names test `{filters[-1]}`, which does not exist yet, and a cargo test filter that matches no test "
                             "exits 0; guard it with `grep -rqw 'fn <test>' crates/<crate>/ &&`")
    return warns


# ---------------------------------------------------------------- git + drift

def git(*args: str) -> str:
    p = subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True)
    return p.stdout if p.returncode == 0 else ""


def git_ok(*args: str) -> bool:
    return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True).returncode == 0


def head_rev() -> str:
    return git("rev-parse", "--short=9", "HEAD").strip()


def anchor_parts(a: str):
    """'path::symbol', 'path:line' or 'path' → (path, symbol); (None, None) for non-path anchors."""
    a = a.strip()
    m = re.match(r"^([A-Za-z0-9_.@/\-]+?)(?:::(.+)|:(\d+(?:-\d+)?))?$", a)
    if not m:
        return None, None
    path = m.group(1)
    if "/" not in path and not (REPO / path).exists():
        return None, None
    sym = m.group(2).split("::")[-1].split("(")[0].strip() if m.group(2) else None
    return path.rstrip("/") if path.endswith("/") else path, sym


def commit_log(since: str | None = None, names: bool = True):
    """[(sha, date, subject, body, [files])] newest first; one pass over git log (merges excluded: their
    commits appear individually)."""
    args = ["log", "--no-merges", "--date=short", "--format=%x1e%h%x1f%cd%x1f%s%x1f%b%x1f"] + (["--name-only"] if names else [])
    if since:
        args.append(f"--since={since}")
    out = []
    for rec in git(*args).split("\x1e")[1:]:
        f = rec.split("\x1f")
        if len(f) < 5:
            continue
        files = [x for x in f[4].splitlines() if x.strip()]
        out.append((f[0], f[1], f[2], f[3], files))
    return out


def _item_since(it) -> str:
    return str(it.get("last_verified") or it.get("created") or "1970-01-01")


def plan_closes():
    """{item id: [(plan path, task id, verdict or None, run_id or None)]} from plans/**/tasks.toml + Graph checkpoints."""
    out = defaultdict(list)
    plans = REPO / "plans"
    if not plans.exists():
        return out
    for tf in plans.rglob("tasks.toml"):
        if any(part.startswith(".") or part == "node_modules" for part in tf.parts):
            continue
        try:
            data = tomllib.loads(tf.read_text())
        except Exception:  # noqa: BLE001
            continue
        tasks = data.get("task") or data.get("tasks") or []
        if not any(t.get("closes") for t in tasks if isinstance(t, dict)):
            continue
        plan_id = (data.get("meta") or {}).get("plan") or tf.parent.name
        cp_file = REPO / ".roko" / "state" / "graph" / plan_id / "checkpoint.json"
        verdicts, run_id = {}, None
        if cp_file.exists():
            try:
                cp = json.loads(cp_file.read_text())
                run_id = cp.get("run_id")
                verdicts = ((cp.get("extensions") or {}).get("roko.gate.verdict@1") or {}).get("value", {}).get("verdicts", {})
            except Exception:  # noqa: BLE001
                pass
        for t in tasks:
            if not isinstance(t, dict):
                continue
            for iid in t.get("closes") or []:
                out[iid].append((str(tf.parent.relative_to(REPO)), t.get("id"), verdicts.get(t.get("id")), run_id))
    return out


def compute_drift(items, stale_days: int = STALE_DAYS, today: dt.date | None = None):
    """Per open item: why its recorded state may be out of date. Git and file reads only; runs no commands."""
    today = today or dt.date.today()
    opened = [i for i in items if i.get("status") in OPEN]
    if not opened:
        return {}
    horizon = min(str(i.get("created") or "1970-01-01") for i in opened)
    log = commit_log(since=horizon)
    by_file = defaultdict(list)
    for c in log:
        for f in c[4]:
            by_file[f].append(c)
    rev_sets = {}
    closes = plan_closes()
    text_cache = {}
    patch_cache = {}

    def patch_mentions(sha, path, symbols):
        """Does commit `sha`'s diff of `path` change a line (or hunk) that names one of `symbols`?"""
        if (sha, path) not in patch_cache:
            patch_cache[(sha, path)] = git("show", "--format=", "-U3", sha, "--", path)
        changed = [ln for ln in patch_cache[(sha, path)].splitlines()
                   if (ln[:1] in "+-" and not ln.startswith(("+++", "---"))) or ln.startswith("@@")]
        return any(re.search(r"\b" + re.escape(sym) + r"\b", ln) for ln in changed for sym in symbols)

    out = {}
    for it in opened:
        since = _item_since(it)
        rev = it.get("last_verified_rev")
        if rev and rev not in rev_sets:
            ok = git_ok("merge-base", "--is-ancestor", rev, "HEAD")
            rev_sets[rev] = {s[:7] for s in git("rev-list", f"{rev}..HEAD").split()} if ok else None

        def after_check(c):
            s = rev_sets.get(rev) if rev else None
            return (c[0][:7] in s) if s is not None else c[1] > since

        d = {"gone": [], "touched": [], "claimed": [], "mentioned": [], "plan_passed": [], "plan_other": [], "stale": False}
        # Per file: the symbols the item names there. A file anchored only by path or line is watched as a whole;
        # a file anchored by symbol counts as changed only when a commit's diff touches one of those symbols.
        symbols, whole = defaultdict(set), set()
        for a in it.get("anchors") or []:
            path, sym = anchor_parts(a)
            if path:
                (symbols[path].add(sym) if sym else whole.add(path))
        own = str(it["_path"].relative_to(REPO))
        for a in it.get("anchors") or []:
            path, sym = anchor_parts(a)
            if not path:
                continue
            p = REPO / path
            if not p.exists():
                d["gone"].append(a)
                continue
            if sym and p.is_file():
                if path not in text_cache:
                    try:
                        text_cache[path] = p.read_text(errors="replace")
                    except Exception:  # noqa: BLE001
                        text_cache[path] = ""
                if not re.search(r"\b" + re.escape(sym) + r"\b", text_cache[path]):
                    d["gone"].append(a)
            hits = by_file.get(path, []) if p.is_file() else [c for f, cs in by_file.items() if f.startswith(path + "/") for c in cs]
            for c in hits:
                if not after_check(c) or own in c[4] or (c[0], c[2]) in {(t[0], t[2]) for t in d["touched"]}:
                    continue
                if path not in whole and symbols.get(path) and not patch_mentions(c[0], path, symbols[path]):
                    continue
                d["touched"].append((c[0], c[1], c[2], path))
        created = str(it.get("created") or "1970-01-01")
        for c in log:
            msg = c[2] + "\n" + c[3]
            if it["id"] not in msg:
                continue
            closing = any(it["id"] in m.group(1) for m in CLOSE_RE.finditer(msg))
            if closing and c[1] >= created:
                d["claimed"].append((c[0], c[1], c[2]))
            elif after_check(c) and own not in c[4]:  # a commit that also edits the item already accounted for it
                d["mentioned"].append((c[0], c[1], c[2]))
        for plan, task, verdict, run_id in closes.get(it["id"], []):
            (d["plan_passed"] if verdict == "passed" else d["plan_other"]).append((plan, task, verdict, run_id))
        try:
            d["stale"] = (today - dt.date.fromisoformat(since)).days > stale_days
        except ValueError:
            d["stale"] = True
        d["touched"].sort(key=lambda t: t[1], reverse=True)
        if d["gone"] or d["touched"] or d["claimed"] or d["mentioned"] or d["plan_passed"] or d["stale"]:
            out[it["id"]] = d
    return out


def render_drift(root: Path, items, drift, head: str) -> list[str]:
    by_id = {i["id"]: i for i in items}
    link = lambda it: f"[{it['id']}]({it['_path'].relative_to(root)})"  # noqa: E731
    groups = {"likely": [], "gone": [], "touched": [], "mentioned": [], "stale": []}
    for iid, d in drift.items():
        if d["claimed"] or d["plan_passed"]:
            groups["likely"].append(iid)
        elif d["gone"]:
            groups["gone"].append(iid)
        elif d["touched"]:
            groups["touched"].append(iid)
        elif d["mentioned"]:
            groups["mentioned"].append(iid)
        elif d["stale"]:
            groups["stale"].append(iid)
    key = lambda iid: sev_key(by_id[iid])  # noqa: E731
    out = ["# Drift: open items to re-check", "", GEN_NOTE, "",
           f"At HEAD `{head}`: open items whose recorded state may be out of date. Re-check each one against the code, "
           "then close it (`tools/work.py close`) or refresh `last_verified`. `tools/work.py sync` closes the \"likely done\" "
           "ones whose closure is declared by a commit trailer or a passed plan task. Procedure: `work/README.md`, "
           "\"Keeping the graph current\".", ""]
    titles = [("likely", "Likely done: a commit or a passed plan task says it closes them"),
              ("gone", "Anchor gone: the code it points at no longer exists"),
              ("touched", "Code changed since the last check"),
              ("mentioned", "Mentioned in a commit since the last check"),
              ("stale", f"Not checked for more than {STALE_DAYS} days")]
    for g, title in titles:
        ids = sorted(groups[g], key=key)
        out += [f"## {title} ({len(ids)})", ""]
        for iid in ids:
            it, d = by_id[iid], drift[iid]
            why = []
            why += [f"{c[0]} says it closes it" for c in d["claimed"][:2]]
            why += [f"plan task `{p}#{t}` passed" for p, t, _, _ in d["plan_passed"][:2]]
            why += [f"`{a}` not found" for a in d["gone"][:2]]
            if d["touched"] and g in ("touched", "gone", "likely"):
                shas = []
                for t in d["touched"]:
                    if t[0] not in shas:
                        shas.append(t[0])
                why.append(f"{len(shas)} commit(s) touched its anchors since {it.get('last_verified_rev') or it.get('last_verified')}"
                           f" (latest {d['touched'][0][0]} {d['touched'][0][2][:60]!r})")
            if d["mentioned"] and g == "mentioned":
                why.append(f"mentioned in {', '.join(c[0] for c in d['mentioned'][:3])}")
            if g == "stale":
                why.append(f"last checked {it.get('last_verified') or 'never'}")
            out.append(f"- **{it['severity'].upper()}** {link(it)} {it['title']} — {'; '.join(why)}")
        out += ["- none", ""] if not ids else [""]
    return out


def drift_summary(drift) -> str:
    c = Counter()
    for d in drift.values():
        if d["claimed"] or d["plan_passed"]:
            c["likely done"] += 1
        elif d["gone"]:
            c["anchor gone"] += 1
        elif d["touched"]:
            c["changed since checked"] += 1
        elif d["mentioned"]:
            c["mentioned in commits"] += 1
        elif d["stale"]:
            c["stale"] += 1
    order = ["likely done", "anchor gone", "changed since checked", "mentioned in commits", "stale"]
    return " · ".join(f"{c[k]} {k}" for k in order if c[k])


# ---------------------------------------------------------------- claims + picking work

CLAIM_TTL_HOURS = 24
SIZES = ["S", "M", "L"]


def main_root() -> Path:
    """The main worktree (claims are shared by every worktree of the repo, so they live there)."""
    common = subprocess.run(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"], cwd=REPO,
                            capture_output=True, text=True).stdout.strip()
    return Path(common).parent if common else REPO


def claims_dir() -> Path:
    return main_root() / ".roko" / "work-claims"


def load_claims(ttl_hours: int = CLAIM_TTL_HOURS):
    """{id: claim dict with 'age_h' and 'stale'} from .roko/work-claims/*.json."""
    out = {}
    d = claims_dir()
    for f in sorted(d.glob("*.json")) if d.exists() else []:
        try:
            c = json.loads(f.read_text())
            age = (time.time() - dt.datetime.fromisoformat(c["at"]).timestamp()) / 3600
        except Exception:  # noqa: BLE001
            continue
        c["age_h"] = round(age, 1)
        c["stale"] = age > ttl_hours
        out[c["id"]] = c
    return out


def prune_claims():
    """Drop claims whose item is no longer open in the main checkout (it was merged closed, or parked)."""
    d = claims_dir()
    if not d.exists():
        return []
    main = main_root()
    gone = []
    for f in d.glob("*.json"):
        iid = f.stem
        hits = [p for sub in ("work/items", "work/parked", ".roko/work-local/items") for p in (main / sub).glob(f"{iid}-*.md")]
        try:
            status = tomllib.loads(re.match(r"\+\+\+\n(.*?)\n\+\+\+", hits[0].read_text(), re.S).group(1)).get("status") if hits else None
        except Exception:  # noqa: BLE001
            continue
        if status not in OPEN:
            f.unlink()
            gone.append(iid)
    return gone


def footprint(it) -> set[str]:
    """Files (or directories) an item's anchors point at: two items with overlapping footprints conflict."""
    return {p for p, _ in (anchor_parts(a) for a in it.get("anchors") or []) if p}


def overlaps(a: set[str], b: set[str]) -> bool:
    return any(x == y or x.startswith(y + "/") or y.startswith(x + "/") for x in a for y in b)


def goal_order():
    return {g["key"]: n for n, g in enumerate(load_goals())}


def pick_key(it, order):
    return (order.get(it.get("goal"), len(order)),) + now_key(it)


def pick_next(items, n: int = 1, goal: str | None = None, max_size: str | None = None, claims=None):
    """Top-priority open items that a worker can start now, pairwise free of file conflicts.

    Skips: claimed items (live claims), items on hold, unverified items, decisions/questions (they need a human), items whose
    depends_on are still open, items larger than max_size, and items whose footprint overlaps a claimed item or an
    item already picked. Returns (picked, skipped_reasons)."""
    claims = load_claims() if claims is None else claims
    live = {k: c for k, c in claims.items() if not c["stale"]}
    by_id = {i["id"]: i for i in items}
    busy = set().union(*(footprint(by_id[k]) for k in live if k in by_id)) if live else set()
    order = goal_order()
    cands = [i for i in items if i.get("status") == "open" and i.get("triage") == "verified" and not i.get("hold")
             and i.get("kind") not in ("decision", "question") and i["id"] not in live
             and (goal is None or i.get("goal") == goal)]
    picked, skipped = [], Counter()
    for it in sorted(cands, key=lambda i: pick_key(i, order)):
        if len(picked) >= n:
            break
        deps = [d for d in (it.get("links") or {}).get("depends_on", []) or [] if by_id.get(d, {}).get("status") in OPEN]
        if deps:
            skipped["waits on an open dependency"] += 1
            continue
        if max_size and it.get("size") in SIZES and SIZES.index(it["size"]) > SIZES.index(max_size):
            skipped[f"larger than {max_size}"] += 1
            continue
        fp = footprint(it)
        if fp and overlaps(fp, busy):
            skipped["touches files of a claimed or already-picked item"] += 1
            continue
        picked.append(it)
        busy |= fp
    return picked, skipped


def cmd_next(a):
    prune_claims()
    items = [i for i in load("work")[0]]
    picked, skipped = pick_next(items, a.n, a.goal, a.max_size)
    order = goal_order()
    if a.json:
        rows = [{"id": i["id"], "title": i["title"], "goal": i.get("goal"), "severity": i["severity"], "size": i.get("size"),
                 "path": str(i["_path"].relative_to(REPO)), "anchors": i.get("anchors") or [],
                 "verify": [v.get("command") for v in i.get("verify") or []]} for i in picked]
        json.dump(rows, sys.stdout, indent=1)
        print()
        return
    goals = {g["key"]: g["title"] for g in load_goals()}
    for i in picked:
        fp = footprint(i)
        print(f"{i['id']}  [{i['severity']}{'/' + i['size'] if i.get('size') else ''}] {i['title']}")
        print(f"    goal: {goals.get(i.get('goal'), 'later (no goal)')} · file: {i['_path'].relative_to(REPO)}"
              + ("" if fp else " · footprint unknown (no path anchors): check for conflicts by hand"))
    if not picked:
        print("nothing available")
    if skipped:
        print("skipped: " + ", ".join(f"{v} {k}" for k, v in skipped.items()))


def cmd_claim(a):
    idx = index()
    d = claims_dir()
    d.mkdir(parents=True, exist_ok=True)
    live = {k for k, c in load_claims().items() if not c["stale"]}
    session = session_name(a.session, a.by)
    for iid in a.ids:
        it = idx.get(iid)
        if it is None or it.get("status") not in OPEN:
            sys.exit(f"{iid}: not found or not open")
        if iid in live and not a.force:
            c = load_claims()[iid]
            sys.exit(f"{iid}: already claimed by {c.get('by')} {c['age_h']}h ago (use --force to take over a claim you know is dead)")
        now = dt.datetime.now().astimezone()
        size = a.size or it.get("size")
        rec = {"id": iid, "by": a.by, "at": now.isoformat(timespec="seconds"), "claimed_at": utc_ts(now),
               "branch": a.branch, "worktree": a.worktree, "title": it["title"], "session": session,
               "executor": a.executor, "via": a.via, "size": size}
        f = d / f"{iid}.json"
        try:
            fd = os.open(f, os.O_WRONLY | os.O_CREAT | (0 if a.force else os.O_EXCL), 0o644)
        except FileExistsError:
            sys.exit(f"{iid}: claimed by someone else a moment ago")
        with os.fdopen(fd, "w") as fh:
            fh.write(json.dumps(rec, indent=1) + "\n")
        log_event("claim", iid, session=session, executor=a.executor, via=a.via, branch=a.branch, by=a.by,
                  size=size, claimed_at=rec["claimed_at"], force=True if a.force else None)
        print(f"claimed {iid} for {a.by}")


def cmd_release(a):
    claims = load_claims()
    for iid in a.ids:
        f = claims_dir() / f"{iid}.json"
        if f.exists():
            c = claims.get(iid) or {}
            # Logged before the claim goes: the event keeps what the claim knew.
            log_event("release", iid, session=session_name(a.session, c.get("session"), c.get("by")),
                      executor=c.get("executor"), via=c.get("via"), branch=c.get("branch"), by=c.get("by"),
                      reason=a.reason, size=c.get("size"), claimed_at=c.get("claimed_at"))
            f.unlink()
            print(f"released {iid}")
        else:
            print(f"{iid}: no claim")


